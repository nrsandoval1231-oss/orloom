import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { cp, lstat, mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';

const exec = promisify(execFile), sha = b => createHash('sha256').update(b).digest('hex');
const source = path.resolve(process.env.ORLOOM_PROOF_SOURCE_REPO ?? '../orloom-suite');
const payload = path.resolve(process.env.ORLOOM_PROOF_RUNTIME_FILES ?? 'runtime-files');
const output = path.resolve(process.env.ORLOOM_PROOF_TRANSFER_DIR ?? 'transfer');
const candidate = process.env.ORLOOM_PROOF_CANDIDATE_SHA, base = process.env.ORLOOM_PROOF_BASE_SHA;
const suiteManifestSha256 = process.env.ORLOOM_PROOF_SOURCE_MANIFEST_SHA256;
const ref = process.env.ORLOOM_PROOF_SOURCE_REF ?? 'refs/heads/feat/trusted-verification-suite';
for (const [v, re] of [[candidate,/^[a-f0-9]{40}$/],[base,/^[a-f0-9]{40}$/],[suiteManifestSha256,/^[a-f0-9]{64}$/]]) assert.ok(re.test(v ?? ''), 'invalid transfer identity input');
const git = async (...args) => (await exec('git', args, { cwd: source, windowsHide: true, env: { ...process.env, GIT_CONFIG_NOSYSTEM:'1', GIT_CONFIG_GLOBAL:process.platform==='win32'?'NUL':'/dev/null' } })).stdout.trim();
assert.equal(await git('rev-parse','HEAD'), candidate); assert.equal(await git('rev-parse',`${ref}^{commit}`),candidate);
assert.equal(await git('status','--porcelain=v1'),'','source checkout must be clean');
await git('merge-base','--is-ancestor',base,candidate);
const suiteBytes = await readFile(path.join(source,'.agent/ORL-C3-SUITE-MANIFEST.sha256'));
assert.equal(sha(suiteBytes),suiteManifestSha256,'suite source manifest digest mismatch');
const suiteRows = suiteBytes.toString('utf8').trimEnd().split('\n');
assert.equal(suiteRows.length,116,'expected reviewed 116-file suite manifest');
const payloadIdentity = JSON.parse(await readFile(path.join(payload,'runtime-files-identity.json'),'utf8'));
assert.equal(payloadIdentity.candidate,candidate); assert.equal(payloadIdentity.sourceManifestSha256,suiteManifestSha256);
const payloadManifest = await readFile(path.join(payload,'runtime-files.sha256'));
assert.equal(sha(payloadManifest),payloadIdentity.payloadManifestSha256);
try { await lstat(output); throw new Error('transfer output exists; refusing overwrite'); } catch(e) { if(e.code!=='ENOENT') throw e; }
await mkdir(output,{mode:0o700});
const bundle = path.join(output,'candidate.bundle');
await exec('git',['bundle','create',bundle,ref],{cwd:source,windowsHide:true});
const heads=(await exec('git',['bundle','list-heads',bundle],{cwd:source,windowsHide:true})).stdout.trim();
assert.equal(heads,`${candidate} ${ref}`,'bundle must expose only the exact candidate branch');
await exec('git',['bundle','verify',bundle],{cwd:source,windowsHide:true});
await cp(payload,path.join(output,'runtime-files'),{recursive:true,errorOnExist:true,force:false});
const bundleSha256=sha(await readFile(bundle));
const identity={format:'orl-c3-suite-transfer-v1',candidateSha:candidate,baseSha:base,sourceRef:ref,suiteManifestSha256,suiteFileCount:suiteRows.length,bundleSha256,payloadManifestSha256:payloadIdentity.payloadManifestSha256};
await writeFile(path.join(output,'candidate-identity.json'),`${JSON.stringify(identity,null,2)}\n`,{flag:'wx',mode:0o400});
process.stdout.write(`${JSON.stringify(identity)}\n`);
